// Rebuild docs/ingredient-web.js: the data behind the project page's ingredient
// web. A maintainer one-off like `npm run assets`: the output is committed, CI
// never runs it, and the page needs no build step or fetch to draw it.
//
//   npm run docs:web
//
// Reads the repo's own catalogue (every migration, then the seed, into an
// in-memory SQLite, the way worker/data-integrity.test.ts does), folds it
// through shared/families.ts and shared/pack.ts, and writes the pictures as
// plain numbers. Node strips the types from those two files itself, which is
// why both import nothing but types: change that and this stops running.
//
// What goes on a PUBLIC page, and what doesn't. The pantry (ingredient names and
// how many dishes use each) is aggregate and safe. Per-dish ingredient lists are
// not: any dish could be a Special nobody has played yet. So the page's "try two
// plates" explorer ships a short, hand-picked set of classics (PLATES below),
// and the generator refuses to run if one has gone missing rather than quietly
// shrinking it.

import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import Database from "better-sqlite3";
import { classify, familyOf, FAMILIES, FAMILY_GROUPS, groupOf, nearRate, STAPLES } from "../shared/families.ts";
import { packWeb } from "../shared/pack.ts";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");

const PLATES = {
  kitchen: [
    "Pad Thai", "Shrimp Scampi", "Spaghetti Carbonara", "Ramen", "Pho", "Hamburger", "Chicken Tikka Masala",
    "Paella", "Risotto alla Milanese", "Greek Salad", "Beef Stroganoff", "Margherita Pizza", "Lasagna",
    "Fettuccine Alfredo", "Cacio e Pepe", "Shakshuka", "Tacos al Pastor", "Pierogi",
  ],
  bar: ["Negroni", "Old Fashioned", "Margarita", "Mojito", "Daiquiri", "Tom Collins", "Whiskey Sour", "Moscow Mule"],
};

const db = new Database(":memory:");
db.pragma("foreign_keys = ON");
const dir = join(ROOT, "migrations");
for (const f of readdirSync(dir).filter((n) => n.endsWith(".sql")).sort()) db.exec(readFileSync(join(dir, f), "utf8"));
db.exec(readFileSync(join(ROOT, "seed", "seed.sql"), "utf8"));

const read = (table) =>
  db.prepare(`SELECT name, country, ingredients FROM ${table} WHERE is_active = 1`).all().map((r) => ({
    name: r.name,
    country: r.country,
    ingredients: JSON.parse(r.ingredients),
  }));
const catalogue = { kitchen: read("dishes"), bar: read("drinks") };

const dotRadius = (n) => 4 + Math.sqrt(n) * 2.6;
const ODD = { staple: "Everywhere, no cousins", standalone: "Stands alone" };

function menu(items) {
  const counts = new Map();
  for (const it of items) for (const i of it.ingredients) counts.set(i, (counts.get(i) ?? 0) + 1);
  const by = new Map();
  for (const [ing] of counts) {
    const kind = classify(ing);
    const key = kind === "family" ? familyOf(ing) : kind === "unclassified" ? "standalone" : kind;
    by.set(key, [...(by.get(key) ?? []), ing]);
  }
  const total = (k) => by.get(k).reduce((n, i) => n + counts.get(i), 0);
  const odd = ["staple", "standalone"].filter((k) => by.has(k));
  const fams = [...by.keys()].filter((k) => !odd.includes(k)).sort((a, b) => total(b) - total(a) || a.localeCompare(b));
  const keys = [...fams, ...odd];
  const web = packWeb(
    keys.map((k) => ({
      key: k,
      leaves: by.get(k).sort((a, b) => counts.get(b) - counts.get(a) || a.localeCompare(b)).map((i) => ({ key: i, r: dotRadius(counts.get(i)) })),
    })),
  );
  const round = (n) => Math.round(n * 10) / 10;
  return {
    total: items.length,
    ingredients: counts.size,
    rate: nearRate(items.map((i) => ({ name: i.name, ingredients: i.ingredients }))),
    bounds: Object.fromEntries(Object.entries(web.bounds).map(([k, v]) => [k, round(v)])),
    rings: web.groups.map((g) => ({
      k: g.key,
      label: ODD[g.key] ?? g.key,
      odd: g.key in ODD,
      g: groupOf(g.key),
      x: round(g.x),
      y: round(g.y),
      r: round(g.r),
      dots: g.leaves.map((l) => ({ k: l.key, n: counts.get(l.key), x: round(l.x), y: round(l.y), r: round(l.r) })),
    })),
  };
}

const plates = {};
for (const [which, names] of Object.entries(PLATES)) {
  plates[which] = names.map((n) => {
    const row = catalogue[which].find((r) => r.name === n);
    if (!row) throw new Error(`"${n}" is not in the ${which} catalogue: fix PLATES in scripts/build-ingredient-web.mjs`);
    return { name: row.name, country: row.country, ingredients: row.ingredients };
  });
}

const data = {
  generated: new Date().toISOString().slice(0, 10),
  staples: STAPLES,
  families: FAMILIES,
  groups: FAMILY_GROUPS,
  menus: { kitchen: menu(catalogue.kitchen), bar: menu(catalogue.bar) },
  plates,
};

const out =
  "/* GENERATED by scripts/build-ingredient-web.mjs (npm run docs:web). Do not edit.\n" +
  "   A snapshot of the pantry's shape: ingredient names, how many dishes use each, and the\n" +
  "   families that group them. No dish's full ingredient list is in here except the\n" +
  "   hand-picked classics under `plates`. */\n" +
  `window.INGREDIENT_WEB = ${JSON.stringify(data)};\n`;
writeFileSync(join(ROOT, "docs", "ingredient-web.js"), out);
console.log(`docs/ingredient-web.js: ${(out.length / 1024).toFixed(1)} KB`);
console.log(
  `kitchen ${data.menus.kitchen.total} dishes, ${data.menus.kitchen.ingredients} ingredients; ` +
    `bar ${data.menus.bar.total} drinks, ${data.menus.bar.ingredients} ingredients`,
);
